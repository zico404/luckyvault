// LOGO CONCEPT: "The Faceted Mark"
//
// An abstract geometric form inspired by:
// - A gemstone viewed from above (fortune, value, rarity)
// - A vault door's locking mechanism (security, trust)
// - A shield silhouette (protection, confidence)
//
// The shape is a regular octagon with deliberate faceted cuts
// that create an internal star/flower pattern. This represents
// the many layers of security protecting the user's fortune.
//
// At the center, a small diamond cutout represents the
// singular point of access — the user's key to their vault.
//
// GEOMETRY:
// - Outer: regular octagon, all edges equal
// - Inner: 8 facets radiating from center to edges
// - Center: small diamond (rotated square)
// - Symmetry: 8-fold rotational symmetry
//
// CONSTRUCTION:
// - Based on a 100×100 grid
// - Octagon inscribed in a circle of radius 46
// - Inner facets connect midpoints of octagon edges to center
// - Center diamond: 8×8, rotated 45°
//
// COLOR USAGE:
// - Primary: Champagne Gold on dark background
// - Monochrome: single weight, any color
// - Reversed: white on dark
// - Dark: black on light
//
// CLEAR SPACE: minimum 1/4 of mark width on all sides
//
// SIZES:
// - App icon: 1024×1024 canvas, mark at 68%
// - Favicon: 32×32, simplified (no inner facets)
// - Social: 400×400, full detail
// - Monochrome: 16×16, outer shape only
//
// ═══════════════════════════════════════════════════════════════

// APP ICON CONCEPT:
//
// Shape: Rounded square (iOS/Android standard)
// Background: Rich midnight black (#09090B)
// Mark: Champagne gold (#C9A962) centered
// Depth: No drop shadow — flat, premium feel
// Material: Matte, no gloss or gradient on icon itself
// Lighting: Subtle inner glow on the mark edges (simulates
//           light catching the facets)
// Geometry: Mark occupies ~68% of icon canvas
//           Consistent with Apple/Google guidelines
//
// At 24px (notification/small): outer octagon only, no facets
// At 48px: octagon + center diamond
// At 72px+: full detail with facets

// SPLASH SCREEN CONCEPT:
//
// Animation Sequence (2.4s total):
//
// 0.0s — Screen is pure VaultBlack (#09090B)
//
// 0.2s — Mark fades in at 0% opacity, scale 0.8
//         Easing: cubic-bezier(0.16, 1, 0.3, 1) — decelerate
//         Duration: 600ms
//
// 0.4s — Mark reaches 100% opacity, scale 1.0
//         Subtle champagne glow pulse emanates from center
//         Duration: 400ms, fades to 20% opacity
//
// 0.8s — Glow settles to subtle ambient
//         Mark is crisp and centered
//
// 1.2s — Tagline fades in below mark
//         "Your fortune, secured." in TextSecondary
//         Letter-spacing: wide (2sp)
//         Duration: 400ms
//
// 1.8s — Tagline at full opacity
//         Hold for 400ms
//
// 2.2s — Everything fades out together
//         Duration: 200ms
//         Transitions to main app
//
// Background:始终 VaultBlack, no gradient, no texture
// The simplicity IS the luxury.
